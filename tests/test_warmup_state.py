def _cjson(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False).encode("utf-8")


def _sha(value):
    return hashlib.sha256(value).hexdigest()


def _oracle(dtype="float32", literal=LITERAL, bindings=None):
    """Independent struct encoder for the frozen exact envelope contract."""
    bindings = BINDINGS if bindings is None else bindings
    context = dict(format="thesisfedrec.fedgmf_warmup.context", version=1,
                   **bindings, num_items=len(literal["E"]),
                   num_users=sum(len(ids) for _, ids, _ in literal["local"]),
                   embedding_dim=len(literal["w"]), dtype=dtype,
                   party_user_ids=[dict(party_id=p, user_ids=list(ids))
                                   for p, ids, _ in literal["local"]])
    buffers = []

    def add(name, kind, shape, values):
        format_char = {"float32": "f", "float64": "d", "int64": "q"}[kind]
        raw = b"".join(struct.pack("<" + format_char, value) for value in values)
        buffers.append((name, kind, tuple(shape), len(raw), _sha(raw), raw))

    add("item_embeddings", dtype, (context["num_items"], context["embedding_dim"]),
        (value for row in literal["E"] for value in row))
    add("score_weight", dtype, (context["embedding_dim"],), literal["w"])
    add("score_bias", dtype, (), (literal["b"],))
    for party_id, ids, embeddings in literal["local"]:
        add(f"party.{party_id}.user_ids", "int64", (len(ids),), ids)
        add(f"party.{party_id}.user_embeddings", dtype,
            (len(ids), context["embedding_dim"]), (value for row in embeddings for value in row))
    context_id = _sha(_cjson(context))
    snapshot = dict(
        format="thesisfedrec.fedgmf_warmup.snapshot", version=1, context_id=context_id,
        terminal_round_count=len(literal["rounds"]),
        round_summaries=[dict(round_index=i, selected_party_ids=list(selected),
                              total_positive_interactions=count)
                         for i, selected, count in literal["rounds"]],
        buffers=[dict(name=name, dtype=kind, shape=list(shape), nbytes=size, sha256=digest)
                 for name, kind, shape, size, digest, _ in buffers],
    )
    snapshot_id = _sha(_cjson(snapshot))
    file = dict(format="thesisfedrec.fedgmf_warmup.file", version=1,
                context_id=context_id, snapshot_id=snapshot_id, context=context, snapshot=snapshot,
                tensors=[dict(name=name, data=base64.b64encode(raw).decode("ascii"))
                         for name, _, _, _, _, raw in buffers])
    return context, snapshot, tuple(buffers), file, _cjson(file) + b"\n"


def _result(dtype=torch.float32):
    shared = dict(item_embeddings=torch.tensor(LITERAL["E"], dtype=dtype),
                  prediction_weight=torch.tensor([LITERAL["w"]], dtype=dtype),
                  prediction_bias=torch.tensor([LITERAL["b"]], dtype=dtype))
    local = {p: FedGMFLocalState(user_ids=torch.tensor(ids, dtype=torch.int64),
                               user_embeddings=torch.tensor(embeddings, dtype=dtype))
             for p, ids, embeddings in LITERAL["local"]}
    summaries = tuple(runner.FedGMFHFLRoundSummary(
        round_index=i, selected_party_ids=selected, total_positive_interactions=count,
        validation_metrics=_UnreadableDict({"not_consumed": object()}),
    ) for i, selected, count in LITERAL["rounds"])
    return runner.FedGMFHFLFitResult(final_shared_state=shared, final_local_states=local,
                                    validation_candidates=_Unreadable(), round_summaries=summaries)


class _Unreadable:
    def __iter__(self):
        raise AssertionError("unconsumed candidates were traversed")

    def __getattribute__(self, name):
        if name.startswith("__"):
            return object.__getattribute__(self, name)
        raise AssertionError("unconsumed candidates were read")


class _UnreadableDict(dict):
    def __iter__(self):
        raise AssertionError("validation metrics were traversed")

    def items(self):
        raise AssertionError("validation metrics were traversed")

    keys = values = items

    def __getitem__(self, key):
        raise AssertionError("validation metrics were read")



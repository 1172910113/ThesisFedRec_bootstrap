def _capture(result=None, **changes):
    arguments = dict(BINDINGS, expected_num_items=3, expected_num_users=3,
                     expected_party_user_ids=OWNERS)
    arguments.update(changes)
    return ws.capture_fedgmf_warmup(_result() if result is None else result, **arguments)


def _load(path, file=None, **changes):
    file = _oracle()[3] if file is None else file
    arguments = dict(expected_context_id=file["context_id"], expected_snapshot_id=file["snapshot_id"],
                     max_file_bytes=100000)
    arguments.update(changes)
    return ws.load_fedgmf_warmup(path, **arguments)


def _rebind(file):
    """Keep negative fixtures self-consistent except their declared fault."""
    file["context_id"] = _sha(_cjson(file["context"]))
    file["snapshot"]["context_id"] = file["context_id"]
    file["snapshot_id"] = _sha(_cjson(file["snapshot"]))
    return file


def _write(path, file):
    path.write_bytes(_cjson(file) + b"\n")
    return path


def _assert_record(snapshot, dtype="float32", literal=LITERAL):
    context, semantic, buffers, file, _ = _oracle(dtype, literal)
    assert snapshot.protocol_version == 1
    assert snapshot.context_id == file["context_id"]
    assert snapshot.snapshot_id == file["snapshot_id"]
    assert snapshot.buffers == buffers
    assert snapshot.party_user_ids == tuple((p, ids) for p, ids, _ in literal["local"])
    assert snapshot.round_summaries == literal["rounds"]
    assert snapshot.terminal_round_count == len(literal["rounds"])
    assert (snapshot.num_items, snapshot.num_users, snapshot.embedding_dim, snapshot.dtype) == (
        context["num_items"], context["num_users"], context["embedding_dim"], dtype)
    assert semantic["context_id"] == snapshot.context_id
    for name, value in BINDINGS.items():
        assert getattr(snapshot, name) == value


def _assert_immutable(value):
    assert type(value) in (int, str, bytes, tuple)
    if type(value) is tuple:
        for child in value:
            _assert_immutable(child)


@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
def test_independent_context_snapshot_rawbuffers_and_entire_file(dtype, tmp_path, record_property):
    kind = str(dtype).split(".")[-1]
    result = _result(dtype)
    snapshot = _capture(result)
    _assert_record(snapshot, kind)
    assert tuple(field.name for field in fields(snapshot)) == FIELD_NAMES
    assert all(field.kw_only for field in fields(snapshot))
    assert snapshot.__dataclass_params__.frozen and not hasattr(snapshot, "__dict__")
    for field in fields(snapshot):
        _assert_immutable(getattr(snapshot, field.name))
    with pytest.raises(TypeError):
        ws.FedGMFWarmupSnapshot()
    with pytest.raises(TypeError):
        ws.FedGMFWarmupSnapshot(**{field.name: getattr(snapshot, field.name) for field in fields(snapshot)})
    with pytest.raises((FrozenInstanceError, AttributeError)):
        snapshot.num_items = 99
    path = tmp_path / "snapshot.json"
    ws.save_fedgmf_warmup(snapshot, str(path))
    expected = _oracle(kind)[4]
    assert path.read_bytes() == expected
    loaded = _load(path, _oracle(kind)[3])
    _assert_record(loaded, kind)
    assert loaded == snapshot
    # The oracle preserves sign bits, including the negative-zero scalar.
    assert buffers_negative_zero(loaded, kind)
    record_property("literal_oracle_" + kind, json.dumps({
        "context_id": snapshot.context_id, "snapshot_id": snapshot.snapshot_id,
        "file_sha256": _sha(expected), "file_base64": base64.b64encode(expected).decode("ascii"),
        "buffers": [(b[0], b[4]) for b in snapshot.buffers],
    }, sort_keys=True))


def buffers_negative_zero(snapshot, dtype):
    return snapshot.buffers[2][5] == struct.pack("<f" if dtype == "float32" else "<d", -0.0)


def test_source_storage_grad_versions_rng_and_materialized_independence(tmp_path):
    result = _result(torch.float64)
    leaf = torch.nn.Parameter(result.final_shared_state["item_embeddings"].clone())
    nonleaf = leaf.T.contiguous().T
    nonleaf.retain_grad()
    nonleaf.grad = torch.ones_like(nonleaf)
    result.final_shared_state["item_embeddings"] = nonleaf
    result.final_shared_state["prediction_weight"] = torch.nn.Parameter(
        result.final_shared_state["prediction_weight"])
    tensors = list(result.final_shared_state.values()) + [
        tensor for state in result.final_local_states.values()
        for tensor in (state.user_ids, state.user_embeddings)]
    before = [(tensor.detach().clone(), tensor.data_ptr(), tensor._version,
               None if tensor.grad is None else tensor.grad.clone()) for tensor in tensors]
    py_rng, np_rng, torch_rng = random.getstate(), np.random.get_state(), torch.get_rng_state().clone()
    snapshot = _capture(result)
    first = ws.materialize_fedgmf_warmup(snapshot)
    second = ws.materialize_fedgmf_warmup(snapshot)
    ws.save_fedgmf_warmup(snapshot, tmp_path / "immutable.json")
    _load(tmp_path / "immutable.json", _oracle("float64")[3])
    assert random.getstate() == py_rng and torch.equal(torch.get_rng_state(), torch_rng)
    current_np = np.random.get_state()
    assert current_np[0] == np_rng[0] and current_np[2:] == np_rng[2:]
    np.testing.assert_array_equal(current_np[1], np_rng[1])
    for tensor, (value, pointer, version, grad) in zip(tensors, before):
        assert torch.equal(tensor, value) and tensor.data_ptr() == pointer and tensor._version == version
        assert (tensor.grad is None) if grad is None else torch.equal(tensor.grad, grad)
    outputs = list(first[:3]) + [t for state in first[3].values() for t in (state.user_ids, state.user_embeddings)]
    other = list(second[:3]) + [t for state in second[3].values() for t in (state.user_ids, state.user_embeddings)]
    assert [tuple(t.shape) for t in first[:3]] == [(3, 2), (2,), ()]
    assert list(first[3]) == [7, 41]
    assert len({tensor.data_ptr() for tensor in outputs + other + tensors}) == len(outputs + other + tensors)
    for output in outputs + other:
        assert output.device.type == "cpu" and output.is_contiguous() and not output.requires_grad
        assert output.grad_fn is None and output._base is None
    for output in outputs:
        output.fill_(99)
    first[0].resize_(1)
    with torch.no_grad():
        for tensor in tensors:
            tensor.fill_(17)
    _assert_record(snapshot, "float64")
    expected = _oracle("float64")[2]
    for tensor, buffer in zip(other, expected):
        assert tensor.detach().numpy().tobytes() == buffer[5]



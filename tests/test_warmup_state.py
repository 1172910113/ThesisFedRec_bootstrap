def test_reflection_consistent_header_hashes_do_not_bypass_raw_semantics(tmp_path, fault, operation):
    snapshot = _reflection_clone(_capture())
    file = deepcopy(_oracle()[3])
    buffers = list(snapshot.buffers)
    index = 0 if fault == "nonfinite" else 3
    raw = struct.pack("<6f", float("inf"), 0, 2, 3, -4, .5) if index == 0 else struct.pack("<2q", 0, 1)
    row = list(buffers[index])
    row[4], row[5] = _sha(raw), raw
